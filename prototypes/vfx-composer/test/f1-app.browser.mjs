import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath, pathToFileURL} from 'node:url';

const html = fileURLToPath(new URL('../dist/arenamon-vfx-composer.html', import.meta.url));
const evidence = fileURLToPath(new URL('../evidence/f1/', import.meta.url));
const evidenceF11 = fileURLToPath(new URL('../evidence/f1-1/', import.meta.url));
await mkdir(evidence, {recursive: true});
await mkdir(evidenceF11, {recursive: true});
const browser = await chromium.launch({channel: process.env.ARENAMON_BROWSER || 'msedge', headless: true});
try {
  const page = await browser.newPage({viewport: {width: 1400, height: 900}});
  const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => {if (message.type() === 'error') errors.push(message.text());});
  page.on('request', request => {if (/^https?:/.test(request.url())) external.push(request.url());});
  await page.context().setOffline(true);
  await page.goto(pathToFileURL(html).href);
  await page.waitForFunction(() => window.__ARENAMON_VFX_COMPOSER__?.ready === true, null, {timeout: 3000});
  assert.equal(await page.locator('#viewport canvas').count(), 1);
  await page.click('#add-box');
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 1);
  await page.fill('#position-x', '2.5');
  await page.dispatchEvent('#position-x', 'change');
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[0].transform.position[0]), 2.5);
  await page.click('#add-stroke', {timeout: 3000});
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 2);
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[1].geometry.kind), 'stroke');
  await page.click('#undo');
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 1);
  await page.click('#undo');
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[0].transform.position[0]), 0);
  await page.click('#redo');
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[0].transform.position[0]), 2.5);
  await page.click('#redo');
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 2);
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.transformAttached), true);
  await page.reload();
  await page.waitForFunction(() => window.__ARENAMON_VFX_COMPOSER__?.ready === true);
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 2);
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[0].transform.position[0]), 2.5);
  await page.fill('#path-width', '0.3', {timeout: 3000});
  await page.fill('#path-snap', '0.5', {timeout: 3000});
  await page.fill('#path-extrusion', '0.08', {timeout: 3000});
  await page.click('#add-curve', {timeout: 3000});
  await page.click('#add-ribbon', {timeout: 3000});
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 4);
  assert.deepEqual(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes.slice(2).map(node => [node.geometry.kind, node.geometry.width])), [['curve', .3], ['ribbon', .3]]);
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].geometry.extrusion), .08);
  await page.fill('#path-extrusion', '0.2');
  await page.click('#apply-extrusion');
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].geometry.extrusion), .2);
  await page.click('#undo');
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].geometry.extrusion), .08);
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes.slice(2).every(node => node.geometry.points.flat().every(value => Number.isInteger(value * 2)))), true);
  await page.selectOption('#vertex-index', '1', {timeout: 3000});
  await page.fill('#vertex-x', '0.76');
  await page.fill('#vertex-y', '0.26');
  await page.fill('#vertex-z', '0.1');
  await page.click('#apply-vertex');
  assert.deepEqual(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].geometry.points[1]), [1, .5, 0]);
  await page.click('#undo');
  assert.deepEqual(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].geometry.points[1]), [-.5, 1, 0]);
  await page.click('#redo');
  assert.deepEqual(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].geometry.points[1]), [1, .5, 0]);
  await page.fill('#vertex-x', '1.24');
  await page.fill('#vertex-y', '1.26');
  await page.fill('#vertex-z', '0');
  await page.click('#insert-vertex', {timeout: 3000});
  assert.deepEqual(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].geometry.points[2]), [1, 1.5, 0]);
  await page.selectOption('#vertex-index', '2');
  await page.click('#remove-vertex', {timeout: 3000});
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].geometry.points.length), 4);
  await page.click('#undo');
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].geometry.points.length), 5);
  await page.click('#draw-stroke', {timeout: 3000});
  const canvas = await page.locator('#viewport canvas').boundingBox();
  assert.ok(canvas);
  await page.mouse.click(canvas.x + canvas.width * .25, canvas.y + canvas.height * .65);
  await page.mouse.click(canvas.x + canvas.width * .5, canvas.y + canvas.height * .55);
  await page.mouse.click(canvas.x + canvas.width * .72, canvas.y + canvas.height * .68);
  await page.click('#finish-drawing');
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 5);
  assert.deepEqual(await page.evaluate(() => {
    const geometry = window.__ARENAMON_VFX_COMPOSER__.project.nodes.at(-1).geometry;
    return [geometry.kind, geometry.points.length, geometry.points.every(point => point[1] === 0 && point.every(value => Number.isInteger(value * 2)))];
  }), ['stroke', 3, true]);
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.drawing), false);
  await page.click('#undo');
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 4);
  const [download] = await Promise.all([
    page.waitForEvent('download'),
    page.click('#export-project', {timeout: 3000}),
  ]);
  assert.equal(download.suggestedFilename(), 'composer-local.vfx-project.json');
  const exportedPath = await download.path();
  const exported = JSON.parse(await readFile(exportedPath, 'utf8'));
  assert.equal(exported.schema, 'arenamon.vfx-project');
  exported.projectId = 'browser-imported'; exported.effectId = 'browser-imported-effect';
  await page.setInputFiles('#import-project', {name: 'imported.vfx-project.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported))});
  await page.waitForFunction(() => window.__ARENAMON_VFX_COMPOSER__.project.projectId === 'browser-imported');
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 4);
  await page.click('#undo');
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.projectId), 'composer-local');
  const centerBeforePivot = await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.selectedBoundsCenter);
  await page.fill('#pivot-x', '0.5', {timeout: 3000});
  await page.fill('#pivot-y', '0.25');
  await page.fill('#pivot-z', '-0.5');
  await page.click('#apply-pivot');
  assert.deepEqual(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].pivot), [.5, .25, -.5]);
  const centerAfterPivot = await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.selectedBoundsCenter);
  assert.equal(centerAfterPivot.every((value, index) => Math.abs(value - centerBeforePivot[index]) < 1e-6), true);
  await page.click('#undo');
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes[3].pivot), undefined);
  await page.selectOption('#drawing-target', 'surface', {timeout: 3000});
  await page.fill('#path-snap', '0.05');
  const boxScreen = await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.nodeScreenPoint('box-1'));
  await page.click('#draw-stroke');
  await page.mouse.click(boxScreen[0] - 8, boxScreen[1]);
  await page.mouse.click(boxScreen[0], boxScreen[1] - 8);
  await page.mouse.click(boxScreen[0] + 8, boxScreen[1]);
  await page.click('#finish-drawing');
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 5);
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes.at(-1).geometry.points.some(point => point[1] !== 0)), true);
  await page.screenshot({path: `${evidence}/autoria-geometrica.png`, fullPage: true});
  await page.click('#undo');
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), 4);

  await page.fill('#path-width-range', '0.42');
  await page.dispatchEvent('#path-width-range', 'input');
  assert.equal(await page.inputValue('#path-width'), '0.42');
  await page.click('#add-sphere');
  await page.click('#add-plane');
  assert.deepEqual(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes.slice(-2).map(node => node.geometry.kind)), ['sphere', 'plane']);
  await page.click('[data-node-id="ribbon-4"]');
  await page.fill('#path-end-width', '0.1');
  await page.click('#apply-taper');
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes.find(node => node.id === 'ribbon-4').geometry.endWidth), .1);
  await page.click('#toggle-lock');
  const lockedPosition = await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes.find(node => node.id === 'ribbon-4').transform.position[0]);
  await page.fill('#position-x', '7');
  await page.dispatchEvent('#position-x', 'change');
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes.find(node => node.id === 'ribbon-4').transform.position[0]), lockedPosition);
  await page.click('#toggle-lock');
  await page.click('[data-node-id^="sphere-"]');
  await page.click('[data-node-id^="plane-"]', {modifiers: ['Control']});
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.selectedIds.length), 2);
  await page.fill('#position-x', '1.5');
  await page.dispatchEvent('#position-x', 'change');
  assert.deepEqual(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes.slice(-2).map(node => node.transform.position[0])), [1.5, 1.5]);
  const transientBaseline = await page.evaluate(() => JSON.stringify(window.__ARENAMON_VFX_COMPOSER__.project));
  await page.click('#toggle-isolate');
  await page.selectOption('#gizmo-space', 'local');
  await page.click('#toggle-left-panel');
  await page.click('#toggle-right-panel');
  assert.equal(await page.evaluate(baseline => JSON.stringify(window.__ARENAMON_VFX_COMPOSER__.project) === baseline, transientBaseline), true);
  await page.click('#toggle-left-panel');
  await page.click('#toggle-right-panel');
  await page.click('#toggle-isolate');

  await page.selectOption('#drawing-target', 'plane');
  await page.fill('#plane-rotation-x', '45');
  await page.dispatchEvent('#plane-rotation-x', 'change');
  await page.check('#mirror-x');
  await page.fill('#radial-copies', '2');
  await page.dispatchEvent('#radial-copies', 'change');
  const beforeAssisted = await page.locator('#hierarchy [data-node-id]').count();
  await page.click('#draw-stroke');
  const assistedCanvas = await page.locator('#viewport canvas').boundingBox();
  await page.mouse.click(assistedCanvas.x + assistedCanvas.width * .4, assistedCanvas.y + assistedCanvas.height * .58);
  await page.mouse.click(assistedCanvas.x + assistedCanvas.width * .62, assistedCanvas.y + assistedCanvas.height * .48);
  await page.click('#finish-drawing');
  assert.equal(await page.locator('#hierarchy [data-node-id]').count(), beforeAssisted + 4);
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.authoring.radialCopies), 2);
  assert.equal(await page.evaluate(() => window.__ARENAMON_VFX_COMPOSER__.project.nodes.slice(-4).some(node => node.geometry.points.some(point => Math.abs(point[1]) > .01))), true);
  await page.click('#view-front');
  await page.screenshot({path: `${evidenceF11}/frontal.png`, fullPage: true});
  await page.click('#view-side');
  await page.screenshot({path: `${evidenceF11}/lateral.png`, fullPage: true});
  await page.click('#view-perspective');
  assert.equal(errors.length, 0, errors.join('\n'));
  assert.equal(external.length, 0, external.join('\n'));
  await writeFile(`${evidence}/resultado.json`, JSON.stringify({status: 'approved', offline: true, externalRequests: 0, coverage: ['stroke em plano XZ', 'stroke sobre superfície 3D', 'curve', 'ribbon extrudida', 'vértices', 'pivô', 'undo/redo', 'autosave', 'importação/exportação JSON']}, null, 2));
  await writeFile(`${evidenceF11}/resultado.json`, JSON.stringify({status: 'approved', offline: true, externalRequests: 0, coverage: ['plano orientável', 'simetria', 'repetição radial', 'tapering', 'esfera/plano', 'multi-seleção', 'lock', 'isolamento', 'local/global', 'vistas frontal/lateral']}, null, 2));
  console.log('✓ F1.1 fecha autoria geométrica com plano orientável, assistência, tapering, seleção profissional e QA frontal/lateral.');
} finally { await browser.close(); }
